"""Editor-script scaffolding and executeMethod validation.

Unity batch mode can only run *compiled* static C# methods via
``-executeMethod Namespace.Class.Method``. This module

* validates method names and project-editor-script compatibility, and
* scaffolds a ready-to-compile ``Assets/Editor/CliBuild.cs`` build script
  so agents can produce player builds without hand-writing C#.

The generated C# is standard ``BuildPipeline`` usage — the real editor
still performs the build, we only provide the thin entry point.
"""

from __future__ import annotations

import re
from pathlib import Path

_METHOD_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)+$")

_SCAFFOLD_PATH = "Assets/Editor/CliBuild.cs"

_BUILD_TEMPLATE = """\
// Generated by cli-anything-unity. Safe to edit; keep the CliBuild.Perform entry point.
using System;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEngine;

public static class CliBuild
{{
    public static void Perform()
    {{
        string output = GetArg("-cliBuildOutput") ?? "Builds/Player";
        var scenes = EditorBuildSettings.scenes
            .Where(s => s.enabled)
            .Select(s => s.path)
            .ToArray();
        if (scenes.Length == 0)
        {{
            scenes = Directory.GetFiles("Assets", "*.unity", SearchOption.AllDirectories)
                .Select(p => p.Replace("\\\\", "/"))
                .ToArray();
        }}
        if (scenes.Length == 0)
            throw new Exception("No scenes found to build.");

        var target = EditorUserBuildSettings.activeBuildTarget;
        var options = new BuildPlayerOptions
        {{
            scenes = scenes,
            locationPathName = output,
            target = target,
            options = BuildOptions.None,
        }};
        var report = BuildPipeline.BuildPlayer(options);
        if (report.summary.result != BuildResult.Succeeded)
            throw new Exception($"Build failed: {{report.summary.result}} (errors: {{report.summary.totalErrors}})");
        Console.WriteLine($"CliBuild: succeeded -> {{report.summary.outputPath}} ({{report.summary.totalSize}} bytes)");
    }}

    private static string GetArg(string name)
    {{
        var args = Environment.GetCommandLineArgs();
        int i = Array.IndexOf(args, name);
        return (i >= 0 && i + 1 < args.Length) ? args[i + 1] : null;
    }}
}}
"""


def validate_execute_method(method: str) -> str:
    """Require the ``Class.Method`` or ``Namespace.Class.Method`` form Unity
    batch mode expects for ``-executeMethod``."""
    method = (method or "").strip()
    if not _METHOD_RE.match(method):
        raise RuntimeError(
            f"Invalid -executeMethod target '{method}'. Expected "
            "'Namespace.Class.Method' (a static void method in a compiled "
            "Editor script)."
        )
    return method


def has_editor_scripts(project_root: str | Path) -> bool:
    """True if any C# file lives under an ``Editor`` folder (required for
    ``-executeMethod``; Unity compiles those into Assembly-CSharp-Editor)."""
    root = Path(project_root) / "Assets"
    if not root.is_dir():
        return False
    for path in root.rglob("*.cs"):
        if "editor" in path.parent.name.lower():
            return True
    return False


def scaffold_prefab_tools(project_root: str | Path, force: bool = False) -> dict:
    """Write ``Assets/Editor/CliPrefabTools.cs`` into the project."""
    root = Path(project_root)
    if not (root / "Assets").is_dir():
        raise RuntimeError(f"Not a Unity project (missing Assets/): {root}")
    target = root / "Assets" / "Editor" / "CliPrefabTools.cs"
    if target.exists() and not force:
        raise RuntimeError(
            f"{target} already exists. Re-run with --force to overwrite."
        )
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(_PREFAB_TOOLS_TEMPLATE, encoding="utf-8")
    return {"path": str(target), "entry_method": "CliPrefabTools.Apply"}


def scaffold_build_script(project_root: str | Path, force: bool = False) -> dict:
    """Write ``Assets/Editor/CliBuild.cs`` into the project."""
    root = Path(project_root)
    if not (root / "Assets").is_dir():
        raise RuntimeError(f"Not a Unity project (missing Assets/): {root}")
    target = root / "Assets" / "Editor" / "CliBuild.cs"
    if target.exists() and not force:
        raise RuntimeError(
            f"{target} already exists. Re-run with --force to overwrite."
        )
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(_BUILD_TEMPLATE.format(), encoding="utf-8")
    return {"path": str(target), "entry_method": "CliBuild.Perform"}


_PREFAB_TOOLS_TEMPLATE = """\
// Generated by cli-anything-unity. Safe to edit; keep the Apply/Create/CreateFromScene entry points.
using System;
using System.Globalization;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

public static class CliPrefabTools
{
    public static void Apply()
    {
        string path = GetArg("-prefabPath");
        if (string.IsNullOrEmpty(path))
            throw new Exception("Missing -prefabPath argument.");

        var contents = PrefabUtility.LoadPrefabContents(path);
        try
        {
            string rename = GetArg("-prefabRename");
            if (!string.IsNullOrEmpty(rename))
                contents.name = rename;

            string setActive = GetArg("-prefabSetActive");
            if (setActive != null)
                contents.SetActive(string.Equals(setActive, "true", StringComparison.OrdinalIgnoreCase));

            string pos = GetArg("-prefabPosition");
            if (!string.IsNullOrEmpty(pos))
            {
                var parts = pos.Split(',');
                if (parts.Length != 3)
                    throw new Exception("-prefabPosition expects 'x,y,z', got '" + pos + "'");
                contents.transform.position = new Vector3(
                    float.Parse(parts[0], CultureInfo.InvariantCulture),
                    float.Parse(parts[1], CultureInfo.InvariantCulture),
                    float.Parse(parts[2], CultureInfo.InvariantCulture));
            }

            PrefabUtility.SaveAsPrefabAsset(contents, path);
            Console.WriteLine("CliPrefabTools: applied edits to " + path);
        }
        finally
        {
            PrefabUtility.DestroyPrefabContents(contents);
        }
    }

    private static string GetArg(string name)
    {
        var args = Environment.GetCommandLineArgs();
        int i = Array.IndexOf(args, name);
        return (i >= 0 && i + 1 < args.Length) ? args[i + 1] : null;
    }

    public static void Create()
    {
        string path = GetArg("-prefabPath");
        if (string.IsNullOrEmpty(path) || !path.StartsWith("Assets/") || !path.EndsWith(".prefab"))
            throw new Exception("Missing or invalid -prefabPath (expected 'Assets/....prefab').");
        string name = GetArg("-prefabName") ?? System.IO.Path.GetFileNameWithoutExtension(path);
        var go = new GameObject(name);
        try
        {
            var asset = PrefabUtility.SaveAsPrefabAsset(go, path);
            if (asset == null)
                throw new Exception("Failed to create prefab asset at '" + path + "'");
            Console.WriteLine("CliPrefabTools: created prefab '" + path + "'");
        }
        finally
        {
            UnityEngine.Object.DestroyImmediate(go);
        }
    }

    public static void CreateFromScene()
    {
        string scenePath = GetArg("-scenePath");
        string objectPath = GetArg("-gameObjectPath");
        string path = GetArg("-prefabPath");
        if (string.IsNullOrEmpty(scenePath) || !scenePath.StartsWith("Assets/"))
            throw new Exception("Missing or invalid -scenePath (expected 'Assets/....unity').");
        if (string.IsNullOrEmpty(path) || !path.StartsWith("Assets/") || !path.EndsWith(".prefab"))
            throw new Exception("Missing or invalid -prefabPath (expected 'Assets/....prefab').");
        if (string.IsNullOrEmpty(objectPath))
            throw new Exception("Missing -gameObjectPath (hierarchy path like 'Parent/Child').");

        var scene = EditorSceneManager.OpenScene(scenePath, OpenSceneMode.Single);
        var go = GameObject.Find(objectPath);
        if (go == null)
            throw new Exception("GameObject not found in scene: '" + objectPath + "'");

        var asset = PrefabUtility.SaveAsPrefabAsset(go, path);
        if (asset == null)
            throw new Exception("Failed to create prefab asset at '" + path + "'");
        EditorSceneManager.SaveScene(scene);
        Console.WriteLine("CliPrefabTools: created prefab from scene object '" + objectPath + "' -> '" + path + "'");
    }
}
"""
